export const ALL_EXTERNAL_PROBLEMS = [...CODEFORCES_PROBLEMS, ...HACKERRANK_PROBLEMS];

export function mergeCatalogProblems(baseProblems = []) {
  const normalizedBase = baseProblems.map((p) => ({
    ...p,
    platform: p.platform || 'leetcode',
    display_id: p.display_id || `#${p.leetcode_id}`,
    problem_url: p.problem_url || p.leetcode_url,
  }));
  const seen = new Set(normalizedBase.map((p) => p.slug));
  const extras = ALL_EXTERNAL_PROBLEMS.filter((p) => !seen.has(p.slug));
  return [...normalizedBase, ...extras];
}

export function problemPlatformLabel(platform) {
  if (platform === 'codeforces') return 'Codeforces';
  if (platform === 'hackerrank') return 'HackerRank';
  return 'LeetCode';
}

export function problemPlatformBadge(platform) {
  if (platform === 'codeforces') return 'CF';
  if (platform === 'hackerrank') return 'HR';
  return 'LC';
}
